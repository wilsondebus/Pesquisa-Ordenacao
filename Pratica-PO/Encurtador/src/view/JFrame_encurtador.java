    private void jButton_testarLocalActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton_testarLocalActionPerformed
        String urlStr = jTextField_linkEncurtado.getText();
        String urlOriginal; 
        
        if(urlStr.isEmpty()){
            urlOriginal = Encurtador.buscarLinkEncurtado(urlStr, meusLinks);
            JOptionPane.showMessageDialog(this, urlOriginal);
        }
    }//GEN-LAST:event_jButton_testarLocalActionPerformed

